/**
 * Friendly text for an API error. A code without a sentence shows the generic Dutch sentence: the message of the
 * server is English and meant for developers, so it is never shown.
 * @param {{ code?: string, message?: string }} err
 * @returns {string}
 */
export function errorText(err) {
  const table = /** @type {Record<string, string>} */ (S.errors);
  return table[err.code ?? ''] ?? S.errors.error;
}

/**
 * Friendly text for a per-field validation code; an unknown code shows the generic Dutch sentence.
 * @param {string} code
 * @returns {string}
 */
export function fieldErrorText(code) {
  const table = /** @type {Record<string, string>} */ (S.fieldErrors);
  return table[code] ?? S.errors.error;
}
