/**
 * Friendly text for an API error.
 * @param {{ code?: string, message?: string }} err
 * @returns {string}
 */
export function errorText(err) {
  const table = /** @type {Record<string, string>} */ (S.errors);
  return table[err.code ?? ''] ?? err.message ?? S.errors.error;
}

/**
 * Friendly text for a per-field validation code.
 * @param {string} code
 * @returns {string}
 */
export function fieldErrorText(code) {
  const table = /** @type {Record<string, string>} */ (S.fieldErrors);
  return table[code] ?? code;
}
