const toast = toaster(() => toastEl);

/**
 * Run an action; report success or the API error; then reload the tab.
 * @param {() => Promise<unknown>} action
 * @param {string} [done]
 */
async function perform(action, done) {
  try {
    await action();
    if (done) toast(done);
  } catch (err) {
    toast(errorText(/** @type {Error} */ (err)), true);
  }
  await showTab(activeTab);
}

/**
 * A data table. The wrapper scrolls sideways on a phone, so it is a named,
 * keyboard-focusable region. An empty header text stands for the actions column.
 * @param {string} label what the table lists (its accessible name)
 * @param {string[]} headers
 * @param {Array<Array<unknown>>} rows
 */
function table(label, headers, rows) {
  return h('div', { class: 'table-wrap', role: 'region', 'aria-label': label, tabindex: '0' }, [
    h('table', { class: 'data' }, [
      h('thead', {}, [
        h(
          'tr',
          {},
          headers.map((t) => h('th', { scope: 'col' }, t === '' ? h('span', { class: 'sr-only', text: S.admin.actions }) : t)),
        ),
      ]),
      h('tbody', {}, rows.map((cells) => h('tr', {}, cells.map((c) => h('td', {}, [c]))))),
    ]),
  ]);
}

/**
 * @param {string} label
 * @param {() => void} onclick
 * @param {string} [cls]
 */
function button(label, onclick, cls = '') {
  return h('button', { class: `btn small ${cls}`.trim(), type: 'button', onclick }, label);
}

/** @param {unknown} value */
const text = (value) => (value === null || value === undefined || value === '' ? '–' : String(value));

/**
 * @param {string} name
 * @param {string[]} values
 */
function select(name, values, labels = values) {
  return h(
    'select',
    { name },
    values.map((v, i) => h('option', { value: v, text: labels[i] ?? v })),
  );
}

// ------------------------------------------------------------------- users

async function renderUsers() {
  /** @type {{ users: import('../api.js').User[] }} */
  const { users } = await get('/api/admin/users');
  const me = session.user.id;

  const username = h('input', { type: 'text', name: 'username', autocapitalize: 'none', autocomplete: 'off', spellcheck: 'false' });
  const displayName = h('input', { type: 'text', name: 'displayName', autocomplete: 'off', maxlength: '60' });
  const role = select('role', ['member', 'admin'], [S.admin.users.roleLabel.member, S.admin.users.roleLabel.admin]);
  const password = h('input', { type: 'text', name: 'password', autocomplete: 'off', spellcheck: 'false' });
  const fUser = field(S.admin.users.username, username, S.admin.users.usernameHint);
  const fName = field(S.admin.users.displayName, displayName);
  const fRole = field(S.admin.users.role, role);
  const fPass = field(S.admin.users.password, password, S.admin.users.passwordHint);
  const formError = h('p', { class: 'form-error', role: 'alert', hidden: true });

  // A password generated by the server is shown once, in a card above the form.
  // It is built here on the render that follows the change: the panel is rebuilt
  // after every action, so an element made earlier would already be detached.
  /** @type {HTMLElement | null} */
  let secret = null;
  if (revealed) {
    const titleId = 'secret-title';
    secret = h('div', { class: 'card secret-card', role: 'group', 'aria-labelledby': titleId, tabindex: '-1' }, [
      h('p', { id: titleId, text: S.admin.users.generated(revealed.who) }),
      h('p', {}, [h('span', { class: 'secret', text: revealed.password })]),
    ]);
    revealed = null;
  }

  const createForm = h(
    'form',
    {
      class: 'card',
      novalidate: true,
      onsubmit: async (/** @type {Event} */ e) => {
        e.preventDefault();
        for (const f of [fUser, fName, fRole, fPass]) f.setError(null);
        formError.hidden = true;
        const body = /** @type {Record<string, unknown>} */ ({ username: username.value, displayName: displayName.value, role: role.value });
        if (password.value !== '') body['password'] = password.value;
        try {
          const res = await post('/api/admin/users', body);
          toast(S.admin.users.created);
          if (res.generatedPassword) await reveal(res.user.displayName, res.generatedPassword);
          else await showTab('users');
        } catch (err) {
          const apiErr = /** @type {ApiError} */ (err);
          showFieldErrors({ username: fUser, displayName: fName, role: fRole, password: fPass }, apiErr);
          formError.textContent = errorText(apiErr);
          formError.hidden = false;
        }
      },
    },
    [
      h('h2', { text: S.admin.users.create }),
      h('div', { class: 'inline-form top' }, [fUser.row, fName.row, fRole.row, fPass.row]),
      formError,
      h('button', { class: 'btn primary', type: 'submit' }, S.admin.users.add),
    ],
  );

  const rows = users.map((u) => [
    h('span', {}, [h('strong', { text: u.displayName }), u.id === me ? h('span', { class: 'hint', text: ` (${S.you})` }) : null]),
    u.username,
    S.admin.users.roleLabel[u.role],
    h('span', { class: `badge-status ${u.active ? 'confirmed' : 'declined'}`, text: u.active ? S.admin.users.active : S.admin.users.inactive }),
    h('div', { class: 'actions' }, [
      button(u.active ? S.admin.users.deactivate : S.admin.users.reactivate, () => {
        if (u.active && !confirm(S.admin.users.confirmDeactivate)) return;
        void perform(() => patch(`/api/admin/users/${u.id}`, { active: !u.active }), S.admin.users.updated);
      }, u.active ? 'danger' : ''),
      button(u.role === 'admin' ? S.admin.users.makeMember : S.admin.users.makeAdmin, () =>
        void perform(() => patch(`/api/admin/users/${u.id}`, { role: u.role === 'admin' ? 'member' : 'admin' }), S.admin.users.updated),
      ),
      button(S.admin.users.rename, () => {
        const name = prompt(S.admin.users.renamePrompt, u.displayName);
        if (name?.trim()) void perform(() => patch(`/api/admin/users/${u.id}`, { displayName: name.trim() }), S.admin.users.updated);
      }),
      button(S.admin.users.resetPassword, () => {
        if (!confirm(S.admin.users.confirmReset)) return;
        void (async () => {
          try {
            const res = await post(`/api/admin/users/${u.id}/password`, {});
            await reveal(u.displayName, res.generatedPassword);
          } catch (err) {
            toast(errorText(/** @type {Error} */ (err)), true);
          }
        })();
      }),
    ]),
  ]);

  return h('div', {}, [secret, createForm, table(S.admin.tabs.users, [S.admin.users.name, S.admin.users.username, S.admin.users.role, S.admin.users.status, ''], rows)]);
}

/**
 * Reload the users tab with a generated password on top, and move focus to it.
 * @param {string} who
 * @param {string} password
 */
async function reveal(who, password) {
  revealed = { who, password };
  focusSelector = '.secret-card';
  await showTab('users');
}

