/** @type {import('../api.js').Reservation | null} */
let editingReservation = null;
const resFilter = { status: '', userId: '', from: '', to: '' };

async function renderReservations() {
  const { users } = /** @type {{ users: import('../api.js').User[] }} */ (await get('/api/admin/users'));
  const query = new URLSearchParams();
  if (resFilter.status) query.set('status', resFilter.status);
  if (resFilter.userId) query.set('userId', resFilter.userId);
  const from = resFilter.from ? localInputToUtc(resFilter.from, '00:00', tz) : null;
  const to = resFilter.to ? localInputToUtc(resFilter.to, '23:59', tz) : null;
  if (from) query.set('from', from);
  if (to) query.set('to', to);
  /** @type {{ items: import('../api.js').Reservation[] }} */
  const { items } = await get(`/api/reservations?${query}`);

  const statusSel = select('status', ['', 'confirmed', 'pending', 'declined', 'expired'], [S.admin.reservations.all, S.status.confirmed, S.status.pending, S.status.declined, S.status.expired]);
  statusSel.value = resFilter.status;
  const userSel = select('userId', ['', ...users.map((u) => String(u.id))], [S.admin.reservations.all, ...users.map((u) => u.displayName)]);
  userSel.value = resFilter.userId;
  const fromIn = h('input', { type: 'date', name: 'from', value: resFilter.from });
  const toIn = h('input', { type: 'date', name: 'to', value: resFilter.to });
  /** @param {Event} event */
  const apply = (event) => {
    resFilter.status = statusSel.value;
    resFilter.userId = userSel.value;
    resFilter.from = fromIn.value;
    resFilter.to = toIn.value;
    // Changing a filter rebuilds the panel; keep the keyboard where it was.
    const name = event.currentTarget instanceof Element ? event.currentTarget.getAttribute('name') : null;
    if (name) focusSelector = `.filters [name="${name}"]`;
    void showTab('reservations');
  };
  for (const el of [statusSel, userSel, fromIn, toIn]) el.addEventListener('change', apply);
  const filters = h('div', { class: 'filters' }, [
    field(S.admin.reservations.status, statusSel).row,
    field(S.admin.reservations.user, userSel).row,
    field(S.admin.reservations.from, fromIn).row,
    field(S.admin.reservations.to, toIn).row,
  ]);

  const rows = items.map((r) => [
    r.id,
    r.userName,
    r.suggestion ? r.createdByName : '–',
    h('span', { class: `badge-status ${r.status}`, text: S.status[r.status] }),
    fmtRange(r.start, r.end, tz),
    r.status === 'confirmed' ? kmCell(r) : '–',
    text(r.note),
    h('div', { class: 'actions' }, [
      r.can.edit
        ? button(S.edit, () => {
            editingReservation = r;
            focusSelector = EDITOR_FIRST_CONTROL;
            void showTab('reservations');
          })
        : null,
      r.can.cancel
        ? button(S.admin.reservations.cancelReservation, () => {
            if (!confirm(S.admin.reservations.confirmCancel)) return;
            void perform(() => del(`/api/reservations/${r.id}`), S.admin.reservations.cancelled);
          }, 'danger')
        : null,
    ]),
  ]);

  return h('div', {}, [
    filters,
    editingReservation ? reservationEditor(editingReservation) : null,
    items.length === 0
      ? h('p', { class: 'empty', text: S.admin.reservations.none })
      : table(S.admin.tabs.reservations, ['#', S.admin.reservations.driver, S.admin.reservations.createdBy, S.admin.reservations.status, S.admin.reservations.when, S.admin.usage.kmColumn, S.admin.reservations.note, ''], rows),
  ]);
}

/**
 * The kilometre state of a reservation: registered (with the distance and who drove), started, or missing.
 * @param {import('../api.js').Reservation} r
 */
function kmCell(r) {
  const label = S.admin.usage.kmState[r.kmState];
  const drive = r.drive;
  const detail = drive && r.kmState === 'registered' ? ` ${S.usage.km(drive.distanceKm ?? 0)}, ${drive.userName}` : drive && r.kmState === 'draft' ? ` (${drive.userName})` : '';
  const chip = { missing: 'none', draft: 'requested', registered: 'paid' }[r.kmState];
  return h('span', { class: `chip ${chip}`, text: `${label}${detail}` });
}

/** @param {import('../api.js').Reservation} r */
function reservationEditor(r) {
  const start = dateTimeField(S.reserve.start, r.start, tz);
  const end = dateTimeField(S.reserve.end, r.end, tz);
  const note = h('input', { type: 'text', maxlength: '500', value: r.note, autocomplete: 'off' });
  const fNote = field(S.reserve.note, note);
  const formError = h('p', { class: 'form-error', role: 'alert', hidden: true });
  return h(
    'form',
    {
      class: 'card editor',
      novalidate: true,
      onsubmit: async (/** @type {Event} */ e) => {
        e.preventDefault();
        for (const f of [start, end, fNote]) f.setError(null);
        formError.hidden = true;
        const range = readRange(start, end);
        if (!range) return;
        try {
          await patch(`/api/reservations/${r.id}`, { ...range, note: note.value });
          editingReservation = null;
          toast(S.admin.reservations.saved);
          await showTab('reservations');
        } catch (err) {
          const apiErr = /** @type {ApiError} */ (err);
          showFieldErrors({ start, end, note: fNote }, apiErr);
          formError.textContent = errorText(apiErr);
          formError.hidden = false;
        }
      },
    },
    [
      h('h2', { text: `${S.admin.reservations.editTitle} #${r.id} (${r.userName})` }),
      h('div', { class: 'inline-form' }, [start.row, end.row, fNote.row]),
      formError,
      h('div', { class: 'actions' }, [
        h('button', { class: 'btn primary', type: 'submit' }, S.admin.reservations.save),
        button(S.cancel, () => { editingReservation = null; void showTab('reservations'); }),
      ]),
    ],
  );
}

