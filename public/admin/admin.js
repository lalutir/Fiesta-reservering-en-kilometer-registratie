const TAB_RENDERERS = { users: renderUsers, reservations: renderReservations, usage: renderUsage, retention: renderRetention };

/** @param {'users' | 'reservations' | 'usage' | 'retention'} tab */
async function showTab(tab) {
  activeTab = tab;
  for (const b of root.querySelectorAll('.admin-tabs button')) {
    b.setAttribute('aria-pressed', b.getAttribute('data-tab') === tab ? 'true' : 'false');
  }
  try {
    setContent(panel, await TAB_RENDERERS[tab]());
  } catch (err) {
    setContent(
      panel,
      h('div', { class: 'card error-card' }, [
        h('p', { text: errorText(/** @type {Error} */ (err)) }),
        h('button', { class: 'btn', type: 'button', onclick: () => void showTab(tab) }, S.retry),
      ]),
    );
  }
  // The panel was rebuilt, so whatever had focus is gone: put it back where the person was working.
  if (focusSelector) {
    /** @type {HTMLElement | null} */
    const target = panel.querySelector(focusSelector);
    target?.focus();
    focusSelector = null;
  }
}

function build() {
  panel = h('div', { class: 'panel' });
  const tabs = /** @type {const} */ (['users', 'reservations', 'usage', 'retention']).map((tab) =>
    h('button', { class: 'btn', type: 'button', 'data-tab': tab, 'aria-pressed': 'false', onclick: () => void showTab(tab) }, S.admin.tabs[tab]),
  );
  setContent(
    root,
    h('header', { class: 'admin-head' }, [
      h('h1', { text: S.admin.title }),
      h('div', { class: 'actions' }, [
        h('a', { class: 'btn small', href: '/' }, S.admin.backToApp),
        button(S.admin.refresh, () => void showTab(activeTab)),
      ]),
    ]),
    h('div', { class: 'admin-tabs' }, tabs),
    panel,
  );
}

async function start() {
  setUnauthorizedHandler(() => location.replace('/'));
  try {
    session = await get('/api/auth/me');
  } catch {
    location.replace('/');
    return;
  }
  if (session.user.role !== 'admin') {
    location.replace('/');
    return;
  }
  tz = session.timeZone;
  build();
  await showTab('users');
}

void start();
